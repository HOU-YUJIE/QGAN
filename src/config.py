# Stage 2 (MANUAL): the 16 features actually fed to the QGAN, hand-picked
# from the automated top-25. ORDER MATTERS and is part of the model
# definition: the circuit maps column i -> qubit wire i, wires 0-13 are the
# numerical register, wires 14-15 the discrete flag register.
#
# NOTE (known, deliberate for now): pkt_len_var and pkt_len_std are
# deterministically redundant (std = sqrt(var)). Swapping one out is a
# one-line edit here; do it as a controlled experiment, not silently.
NUMERIC_FEATURES = [
    # ranks 1-14 by session-grouped permutation importance (GroupKFold by
    # session_id, RF, f1_macro, Spearman|rho|>0.90 pre-pruned), computed on
    # the deduped session-split training data. See reports/feature_selection_16.md.
    "bwd_seg_size_avg", "pkt_len_min", "fwd_pkt_len_min", "totlen_bwd_pkts",
    "fwd_pkt_len_max", "bwd_pkt_len_min", "pkt_len_mean", "fwd_pkt_len_std",
    "bwd_pkt_len_std", "flow_byts_s", "fwd_pkt_len_mean", "psh_flag_cnt",
    "down_up_ratio", "fwd_act_data_pkts",
]
DISCRETE_FEATURES = [
    # genuinely discrete flag counts (nunique 8 and 12) for the discrete
    # register wires 14-15; the previous psh features were counts up to ~3200.
    "syn_flag_cnt", "fin_flag_cnt",
]
MANUAL_FEATURES_16 = NUMERIC_FEATURES + DISCRETE_FEATURES

NUM_NUMERIC = len(NUMERIC_FEATURES)   # 14 -> wires 0..13
N_QUBITS = len(MANUAL_FEATURES_16)    # 16
assert N_QUBITS == NUM_NUMERIC + len(DISCRETE_FEATURES)


def assert_feature_frame(df, where: str = "") -> None:
    """Fail fast if a dataframe does not contain the 16 features in order.

    Call before any model consumes data: silently reordered or missing
    columns must crash, not train on the wrong wires.
    """
    cols = [c for c in df.columns if c != LABEL_COLUMN]
    missing = [c for c in MANUAL_FEATURES_16 if c not in cols]
    if missing:
        raise ValueError(f"[{where}] missing features: {missing}")
    if cols[:N_QUBITS] != MANUAL_FEATURES_16:
        raise ValueError(
            f"[{where}] feature column order does not match MANUAL_FEATURES_16; "
            "wire assignment would be wrong. Re-run select_manual_features.py."
        )



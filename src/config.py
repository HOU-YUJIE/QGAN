# Class balancing target: classes with >= TARGET_TOTAL_SAMPLES real training
# rows are treated as majority (undersampled to this number); the rest are
# topped up to this number with synthetic rows.
TARGET_TOTAL_SAMPLES = 2000


def get_majority_labels(train_csv: str = None, threshold: int = TARGET_TOTAL_SAMPLES) -> set:
    """Derive majority classes from actual training counts.

    Replaces the hardcoded {0, 3, 6}: if the label mapping or the data ever
    changes again, this stays correct automatically.
    """
    import pandas as pd
    path = train_csv or FEATURES16_TRAIN
    counts = pd.read_csv(path, usecols=[LABEL_COLUMN])[LABEL_COLUMN].value_counts()
    return set(counts[counts >= threshold].index.astype(int))


def load_label_mapping() -> dict:
    with open(LABEL_MAPPING_FILE, "r", encoding="utf-8") as f:
        return json.load(f)


